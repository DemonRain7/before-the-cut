def col(c):
    """Resolve a palette name, hex string or RGB tuple."""
    if isinstance(c, str):
        if c in PAL:
            return PAL[c]
        return hx(c)
    return tuple(c[:3])


def ramp(r):
    if isinstance(r, str):
        r = RAMPS[r]
    return [col(c) for c in r]


_B4 = np.array([[0, 8, 2, 10], [12, 4, 14, 6], [3, 11, 1, 9], [15, 7, 13, 5]],
               dtype=np.float32) / 16.0 + 1.0 / 32.0


def bayer(h, w):
    return np.tile(_B4, (h // 4 + 1, w // 4 + 1))[:h, :w]


# ---------------------------------------------------------------- canvas
class Canvas:
    def __init__(self, w, h, fill=None):
        self.w, self.h = int(w), int(h)
        self.a = np.zeros((self.h, self.w, 4), dtype=np.uint8)
        if fill is not None:
            self.a[:, :, :3] = col(fill)
            self.a[:, :, 3] = 255

    # ---- masks -----------------------------------------------------
    def grid(self):
        return np.mgrid[0:self.h, 0:self.w]

    def none(self):
        return np.zeros((self.h, self.w), dtype=bool)

    def all(self):
        return np.ones((self.h, self.w), dtype=bool)

    def ell(self, cx, cy, rx, ry):
        yy, xx = self.grid()
        return ((xx - cx) / max(rx, 0.01)) ** 2 + ((yy - cy) / max(ry, 0.01)) ** 2 <= 1.0

    def rect(self, x0, y0, x1, y1):
        """Inclusive pixel rectangle."""
        m = self.none()
        x0, x1 = sorted((int(round(x0)), int(round(x1))))
        y0, y1 = sorted((int(round(y0)), int(round(y1))))
        m[max(y0, 0):max(y1 + 1, 0), max(x0, 0):max(x1 + 1, 0)] = True
        return m

    def poly(self, pts):
        im = Image.new("L", (self.w, self.h), 0)
        ImageDraw.Draw(im).polygon([(float(x), float(y)) for x, y in pts], fill=255)
        return np.array(im) > 0

    def rrect(self, x0, y0, x1, y1, r):
        m = self.rect(x0 + r, y0, x1 - r, y1) | self.rect(x0, y0 + r, x1, y1 - r)
        for cx, cy in ((x0 + r, y0 + r), (x1 - r, y0 + r), (x0 + r, y1 - r), (x1 - r, y1 - r)):
            m |= self.ell(cx, cy, r + 0.3, r + 0.3)
        return m

    def seg(self, pts, width=1):
        im = Image.new("L", (self.w, self.h), 0)
        d = ImageDraw.Draw(im)
        pts = [(float(x), float(y)) for x, y in pts]
        d.line(pts, fill=255, width=width)
        return np.array(im) > 0

    def alpha(self):
        return self.a[:, :, 3] > 0

    # ---- painting --------------------------------------------------
    def fill(self, mask, color, a=255):
        self.a[mask, :3] = col(color)
        self.a[mask, 3] = a
        return self

    def erase(self, mask):
        self.a[mask] = 0
        return self

    def px(self, x, y, color):
        x, y = int(x), int(y)
        if 0 <= x < self.w and 0 <= y < self.h:
            self.a[y, x, :3] = col(color)
            self.a[y, x, 3] = 255
        return self

    def line(self, pts, color, width=1):
        return self.fill(self.seg(pts, width), color)

    def shade(self, mask, rmp, light=(-0.8, 0.25), contrast=1.0, round_px=6.0,
              round_amt=0.5, bias=0.0, dither=0.6, clip=None):
        """Fill mask with tones from a dark-to-light ramp.

        light points toward the light in image space (x right, y down).
        round_amt lifts the interior so shapes read as volumes."""
        if clip is not None:
            mask = mask & clip
        if not mask.any():
            return self
        rmp = ramp(rmp)
        ys, xs = np.nonzero(mask)
        cy, cx = (ys.min() + ys.max()) / 2.0, (xs.min() + xs.max()) / 2.0
        hy = max((ys.max() - ys.min()) / 2.0, 1.0)
        hw = max((xs.max() - xs.min()) / 2.0, 1.0)
        yy, xx = self.grid()
        d = ((xx - cx) / hw) * light[0] + ((yy - cy) / hy) * light[1]
        e = np.clip(ndi.distance_transform_edt(mask) / max(round_px, 0.01), 0, 1)
        v = 0.5 + 0.34 * contrast * d + round_amt * (e - 0.6) * 0.5 + bias
        n = len(rmp)
        idx = np.floor(v * (n - 1) + (bayer(self.h, self.w) - 0.5) * dither + 0.5)
        idx = np.clip(idx, 0, n - 1).astype(int)
        lut = np.array(rmp, dtype=np.uint8)
        self.a[mask, :3] = lut[idx[mask]]
        self.a[mask, 3] = 255
        return self

    def grad(self, mask, rmp, x0, y0, x1, y1, dither=0.9):
        """Linear dithered gradient from (x0,y0) dark to (x1,y1) light."""
        rmp = ramp(rmp)
        yy, xx = self.grid()
        dx, dy = x1 - x0, y1 - y0
        t = ((xx - x0) * dx + (yy - y0) * dy) / max(dx * dx + dy * dy, 1e-6)
        n = len(rmp)
        idx = np.floor(np.clip(t, 0, 1) * (n - 1) + (bayer(self.h, self.w) - 0.5) * dither + 0.5)
        idx = np.clip(idx, 0, n - 1).astype(int)
        lut = np.array(rmp, dtype=np.uint8)
        self.a[mask, :3] = lut[idx[mask]]
        self.a[mask, 3] = 255
        return self

    def radial(self, mask, rmp, cx, cy, r, dither=0.9, power=1.0):
        """Radial dithered falloff: light at the centre, dark at radius r."""
        rmp = ramp(rmp)
        yy, xx = self.grid()
        t = 1.0 - np.clip(np.sqrt((xx - cx) ** 2 + (yy - cy) ** 2) / r, 0, 1) ** power
        n = len(rmp)
        idx = np.floor(t * (n - 1) + (bayer(self.h, self.w) - 0.5) * dither + 0.5)
        idx = np.clip(idx, 0, n - 1).astype(int)
        lut = np.array(rmp, dtype=np.uint8)
        self.a[mask, :3] = lut[idx[mask]]
        self.a[mask, 3] = 255
        return self

    def edge(self, mask, dx, dy):
        """Pixels of mask whose neighbour at (dx,dy) lies outside the mask."""
        sh = np.roll(np.roll(mask, -dy, axis=0), -dx, axis=1)
        if dy > 0:
            sh[-dy:, :] = False
        elif dy < 0:
            sh[:-dy, :] = False
        if dx > 0:
            sh[:, -dx:] = False
        elif dx < 0:
            sh[:, :-dx] = False
        return mask & ~sh

    def rim(self, mask, dx, dy, color, clip=None):
        m = self.edge(mask, dx, dy)
        if clip is not None:
            m &= clip
        return self.fill(m, color)

    def outline(self, color="ink1", mask=None, corners=False):
        """One-pixel outline outside the mask (or the whole silhouette)."""
        m = self.alpha() if mask is None else mask
        st = ndi.generate_binary_structure(2, 2 if corners else 1)
        ring = ndi.binary_dilation(m, structure=st) & ~m
        if mask is not None:
            ring &= ~self.alpha() | ring
        return self.fill(ring, color)

    def inline(self, mask, color):
        """One-pixel line just inside the mask boundary."""
        inner = ndi.binary_erosion(mask)
        return self.fill(mask & ~inner, color)

    def glow(self, mask, color, cx, cy, r, amt=1.0, power=1.0, ry=None):
        """Ordered-dither a colour over the image: strongest at the centre, gone at radius r."""
        yy, xx = self.grid()
        ryv = r if ry is None else ry
        d = np.sqrt(((xx - cx) / float(r)) ** 2 + ((yy - cy) / float(ryv)) ** 2)
        t = (1.0 - np.clip(d, 0, 1)) ** power * amt
        return self.fill(mask & (t > bayer(self.h, self.w)), color)

    def dither(self, mask, color, amt):
        """Flat ordered dither of a colour; amt is a number or a per-pixel array in 0..1."""
        return self.fill(mask & (amt > bayer(self.h, self.w)), color)

    def speckle(self, mask, color, density, seed=1):
        rng = np.random.default_rng(seed)
        m = mask & (rng.random((self.h, self.w)) < density)
        return self.fill(m, color)

    def blit(self, other, x=0, y=0):
        x, y = int(x), int(y)
        sx0, sy0 = max(0, -x), max(0, -y)
        dx0, dy0 = max(0, x), max(0, y)
        w = min(other.w - sx0, self.w - dx0)
        h = min(other.h - sy0, self.h - dy0)
        if w <= 0 or h <= 0:
            return self
        src = other.a[sy0:sy0 + h, sx0:sx0 + w]
        dst = self.a[dy0:dy0 + h, dx0:dx0 + w]
        m = src[:, :, 3] > 0
        dst[m] = src[m]
        return self

    def tint(self, mask, color, amount):
        """Blend toward a colour (used sparingly, then palette is not exact)."""
        c = np.array(col(color), dtype=np.float32)
        px = self.a[mask, :3].astype(np.float32)
        self.a[mask, :3] = np.clip(px * (1 - amount) + c * amount, 0, 255).astype(np.uint8)
        return self

    def remap(self, mask, mapping):
        """Swap exact palette colours inside mask: {from: to}."""
        for a, b in mapping.items():
            ca, cb = col(a), col(b)
            m = mask & (self.a[:, :, 0] == ca[0]) & (self.a[:, :, 1] == ca[1]) & (self.a[:, :, 2] == ca[2])
            self.a[m, :3] = cb
        return self

    # ---- transforms and io ----------------------------------------
    def copy(self):
        c = Canvas(self.w, self.h)
        c.a = self.a.copy()
        return c

    def crop(self, x0, y0, x1, y1):
        c = Canvas(x1 - x0, y1 - y0)
        c.a = self.a[y0:y1, x0:x1].copy()
        return c

    def flip(self):
        c = Canvas(self.w, self.h)
        c.a = self.a[:, ::-1].copy()
        return c

    def scaled(self, n):
        c = Canvas(self.w * n, self.h * n)
        c.a = np.repeat(np.repeat(self.a, n, axis=0), n, axis=1)
        return c

    def image(self):
        return Image.fromarray(self.a, "RGBA")

    def save(self, rel, base=ASSETS):
        path = os.path.join(base, rel)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        self.image().save(path)
        return path


def from_image(path):
    im = Image.open(path).convert("RGBA")
    c = Canvas(im.width, im.height)
    c.a = np.array(im)
    return c


def contact_sheet(items, path, scale=3, bg="teal2", pad=6, per_row=6, label=True):
    """Save labelled sprites side by side for visual review (not shipped)."""
    from font_data import draw_text, text_width
    rows = [items[i:i + per_row] for i in range(0, len(items), per_row)]
    lab_h = 12 if label else 0
    row_h = [max(c.h for _, c in r) + lab_h + pad for r in rows]
    row_w = [sum(max(c.w, text_width(n) if label else 0) + pad for n, c in r) + pad for r in rows]
    sheet = Canvas(max(row_w), sum(row_h) + pad, bg)
    y = pad
    for r, rh in zip(rows, row_h):
        x = pad
        for name, c in r:
            if label:
                draw_text(sheet, x, y, name, "teal6")
            sheet.blit(c, x, y + lab_h)
            x += max(c.w, text_width(name) if label else 0) + pad
        y += rh
    os.makedirs(os.path.dirname(path), exist_ok=True)
    sheet.scaled(scale).image().convert("RGB").save(path)
    return path
